import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { AuthService } from '../services/AuthService.js';
import { addDays, isWeekend, parseIsoDate, todayIso } from '../utils/dates.js';
import { seedLeavePolicy } from './seedLeavePolicy.js';

export const DEMO_PASSWORD = 'Password@123';

/**
 * Creates demo departments, users and leave requests in different workflow states.
 * Leave requests go through the real LeaveService, so the timeline and audit
 * log look exactly like real usage. Dates are relative to today.
 */
export function seedDemoData(services, config) {
  const { users, leaveService } = services;
  const hash = AuthService.hashPassword(DEMO_PASSWORD);
  seedLeavePolicy(services, config); // Codex: holidays etc. (before leave requests are created)

  const engineering = users.createDepartment('Engineering');
  const operations = users.createDepartment('Operations');

  const meera = users.create({ name: 'Meera Nair', email: 'hod@example.com', passwordHash: hash, role: 'HOD', departmentId: engineering });
  const rahul = users.create({ name: 'Rahul Verma', email: 'manager@example.com', passwordHash: hash, role: 'MANAGER', departmentId: engineering, managerId: meera });
  const john = users.create({ name: 'John Doe', email: 'employee@example.com', passwordHash: hash, role: 'EMPLOYEE', departmentId: engineering, managerId: rahul });
  const ananya = users.create({ name: 'Ananya Iyer', email: 'ananya@example.com', passwordHash: hash, role: 'EMPLOYEE', departmentId: engineering, managerId: rahul });

  const vikram = users.create({ name: 'Vikram Rao', email: 'ops.hod@example.com', passwordHash: hash, role: 'HOD', departmentId: operations });
  const sneha = users.create({ name: 'Sneha Kapoor', email: 'ops.manager@example.com', passwordHash: hash, role: 'MANAGER', departmentId: operations, managerId: vikram });
  const karan = users.create({ name: 'Karan Mehta', email: 'ops.employee@example.com', passwordHash: hash, role: 'EMPLOYEE', departmentId: operations, managerId: sneha });

  const u = (id) => users.findById(id);
  const ctx = { ip: 'seed' };
  const today = todayIso();
  const monday = (weeksFromNow) => addDays(startOfWeek(today), weeksFromNow * 7);
  const doc = (title, lines) => writeDemoPdf(config.uploadDir, title, lines);

  // 1. Short leave, waiting for the manager.
  leaveService.create(u(john), { leaveType: 'CASUAL', fromDate: monday(1), toDate: addDays(monday(1), 1), reason: "Family function at my hometown" }, [], ctx);

  // 2. Long leave (5 working days) with a medical certificate: manager approved, now with the HOD.
  const sick = leaveService.create(
    u(ananya),
    { leaveType: 'SICK', fromDate: monday(2), toDate: addDays(monday(2), 4), reason: 'Minor surgery and recovery as advised by my doctor' },
    [doc('medical-certificate.pdf', ['Medical Certificate (demo)', 'Patient: Ananya Iyer', 'Advised rest: 5 days', 'This is sample data generated by the seed script.'])],
    ctx,
  );
  leaveService.approve(u(rahul), sick.id, { comment: 'Medical certificate verified. Get well soon! Forwarding to HOD.' }, ctx);

  // 3. Past leave, approved (leave history).
  const past = leaveService.create(u(john), { leaveType: 'EARNED', fromDate: monday(-2), toDate: addDays(monday(-2), 2), reason: 'Short trip with family' }, [], ctx);
  leaveService.approve(u(rahul), past.id, { comment: 'Enjoy your trip!' }, ctx);

  // 4. Long leave that went through both levels and is fully approved.
  const longApproved = leaveService.create(
    u(john),
    { leaveType: 'SICK', fromDate: monday(-1), toDate: addDays(monday(-1), 3), reason: 'Viral fever, doctor advised complete rest' },
    [doc('doctor-note.pdf', ['Doctor Note (demo)', 'Patient: John Doe', 'Diagnosis: Viral fever', 'Advised rest: 4 days'])],
    ctx,
  );
  leaveService.approve(u(rahul), longApproved.id, { comment: 'Take care.' }, ctx);
  leaveService.approve(u(meera), longApproved.id, { comment: 'Approved. Please hand over pending reviews.' }, ctx);

  // 5. Rejected request with a reason.
  const rejected = leaveService.create(u(john), { leaveType: 'CASUAL', fromDate: addDays(monday(3), 3), toDate: addDays(monday(3), 4), reason: 'Personal work' }, [], ctx);
  leaveService.reject(u(rahul), rejected.id, { comment: 'Release week for the booking service. Can you move this by a week?' }, ctx);

  // 6. Manager asked for more information.
  const info = leaveService.create(u(ananya), { leaveType: 'CASUAL', fromDate: monday(4), toDate: addDays(monday(4), 2), reason: 'Attending a friend\'s wedding' }, [], ctx);
  leaveService.requestInfo(u(rahul), info.id, { comment: 'Who will cover your on-call shift on these dates? Please add a handover plan.' }, ctx);

  // 7. A manager's own leave: their reporting manager is the HOD.
  leaveService.create(u(rahul), { leaveType: 'EARNED', fromDate: addDays(monday(1), 4), toDate: addDays(monday(1), 4), reason: 'Bank and passport office visit' }, [], ctx);

  // 8. Someone on approved leave today (or the next working day).
  const onLeave = nextWorkingDay(today);
  const todayLeave = leaveService.create(u(ananya), { leaveType: 'CASUAL', fromDate: onLeave, toDate: onLeave, reason: 'Moving to a new apartment' }, [], ctx);
  leaveService.approve(u(rahul), todayLeave.id, { comment: '' }, ctx);

  // 9. Operations department: long leave waiting for its manager.
  leaveService.create(
    u(karan),
    { leaveType: 'EARNED', fromDate: monday(3), toDate: addDays(monday(3), 3), reason: 'Annual vacation with family to Goa' },
    [doc('flight-booking.pdf', ['Travel Itinerary (demo)', 'Passenger: Karan Mehta', 'Sample document generated by the seed script.'])],
    ctx,
  );
}

function startOfWeek(iso) {
  const day = parseIsoDate(iso).getUTCDay(); // 0 = Sunday
  return addDays(iso, day === 0 ? -6 : 1 - day);
}

function nextWorkingDay(iso) {
  let date = iso;
  while (isWeekend(parseIsoDate(date))) date = addDays(date, 1);
  return date;
}

/** Writes a small valid one-page PDF and returns a multer-like file descriptor. */
function writeDemoPdf(uploadDir, fileName, lines) {
  const esc = (s) => s.replace(/[\\()]/g, (c) => `\\${c}`);
  const [title, ...rest] = lines;
  const content = `BT /F1 20 Tf 72 720 Td (${esc(title)}) Tj ET\nBT /F1 12 Tf 16 TL 72 680 Td ${rest.map((l) => `(${esc(l)}) Tj T*`).join(' ')} ET`;
  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>',
    `<< /Length ${Buffer.byteLength(content)} >>\nstream\n${content}\nendstream`,
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
  ];
  let pdf = '%PDF-1.4\n';
  const offsets = objects.map((obj, i) => {
    const offset = Buffer.byteLength(pdf);
    pdf += `${i + 1} 0 obj\n${obj}\nendobj\n`;
    return offset;
  });
  const xref = Buffer.byteLength(pdf);
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  pdf += offsets.map((o) => `${String(o).padStart(10, '0')} 00000 n \n`).join('');
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;

  fs.mkdirSync(uploadDir, { recursive: true });
  const storedName = `${Date.now()}-${crypto.randomBytes(12).toString('hex')}.pdf`;
  const filePath = path.join(uploadDir, storedName);
  fs.writeFileSync(filePath, pdf);
  return { originalname: fileName, filename: storedName, mimetype: 'application/pdf', size: Buffer.byteLength(pdf), path: filePath };
}
